#!/usr/bin/env python3
"""After build_db.py: run business questions (sql/06), write qa/dq_report.md and
export the clean core tables + marts to powerbi/csv/ for Power BI Desktop."""
import os, re, json, duckdb, datetime as dt
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
os.chdir(ROOT)
os.makedirs("powerbi/csv", exist_ok=True)
os.makedirs("qa", exist_ok=True)
con = duckdb.connect(os.path.join("db", "berlin_property_ops.duckdb"))

def md_table(df, maxrows=60):
    df = df.head(maxrows)
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        vals = []
        for v in r.values:
            if hasattr(v, "strftime"):
                vals.append(v.strftime("%Y-%m-%d"))
            elif isinstance(v, float) and v != v:
                vals.append("–")
            elif isinstance(v, float):
                vals.append(f"{v:,.3f}".rstrip("0").rstrip(".") if abs(v) < 10 else f"{v:,.0f}")
            else:
                vals.append(str(v))
        out.append("| " + " | ".join(vals) + " |")
    return "\n".join(out)

# ---------------------------------------------------------------- business questions -> sql/results
os.makedirs("sql/results", exist_ok=True)
sql = open("sql/06_business_questions.sql", encoding="utf-8").read()
blocks = re.split(r"\n(?=-- Q\d\d )", sql)
allmd = ["# Query results (synthetic sample, snapshot 2026-09-30)\n", "Generated by `scripts/export.py` from `sql/06_business_questions.sql`.\n"]
for b in blocks:
    m = re.match(r"-- (Q\d\d) (.*)", b.strip())
    if not m:
        continue
    q = b.strip()
    df = con.sql(q).df()
    if m.group(1) == "Q01":
        df = df.T.reset_index(); df.columns = ["kpi", "value"]
        df["value"] = df["value"].astype(float).map(lambda v: f"{v:,.3f}" if abs(v) < 10 else f"{v:,.0f}")
    allmd.append(f"## {m.group(1)} {m.group(2)}\n\n{md_table(df)}\n")
open("sql/results/query_results.md", "w", encoding="utf-8").write("\n".join(allmd))
print("wrote sql/results/query_results.md")

# ---------------------------------------------------------------- QA report
dq = con.sql("SELECT check_id, check_name, table_name, severity, failed_keys, failed_rows, result, handling FROM dq.results").df()
inj = json.load(open("data/raw/_dq_injection_log.json"))
counts = con.sql("""
SELECT 'fact_maintenance_ticket' AS \"table\", (SELECT COUNT(*) FROM raw.fact_maintenance_ticket) raw_rows, (SELECT COUNT(*) FROM core.fact_maintenance_ticket) core_rows
UNION ALL SELECT 'fact_payment', (SELECT COUNT(*) FROM raw.fact_payment), (SELECT COUNT(*) FROM core.fact_payment)
UNION ALL SELECT 'fact_rent_roll', (SELECT COUNT(*) FROM raw.fact_rent_roll), (SELECT COUNT(*) FROM core.fact_rent_roll)
UNION ALL SELECT 'fact_service_charge_statement', (SELECT COUNT(*) FROM raw.fact_service_charge_statement), (SELECT COUNT(*) FROM core.fact_service_charge_statement)
UNION ALL SELECT 'dim_unit', (SELECT COUNT(*) FROM raw.dim_unit), (SELECT COUNT(*) FROM core.dim_unit)""").df()
impact = con.sql("""
SELECT
 (SELECT SUM(amount) FROM raw.fact_payment) - (SELECT SUM(amount) FROM core.fact_payment WHERE TRUE) AS duplicate_payment_eur,
 (SELECT SUM(total_due) FROM dq.quarantine_rent_roll) AS quarantined_soll_eur,
 (SELECT SUM(cost_eur) FROM raw.fact_maintenance_ticket) - (SELECT SUM(cost_eur) FROM core.fact_maintenance_ticket) AS duplicate_ticket_cost_eur""").df().iloc[0]
detected = {"DQ01": "DQ1_duplicate_ticket_rows", "DQ02": "DQ2_resolved_before_created", "DQ03": "DQ3_units_zero_or_null_area",
            "DQ04": "DQ4_orphan_rent_roll_unit_ids", "DQ05": "DQ5_duplicate_bank_refs", "DQ06": "DQ6_statement_issued_before_period_end"}
recon = []
for cid, key in detected.items():
    found = set(con.sql(f"SELECT key FROM dq.failed_keys WHERE check_id = '{cid}'").df()["key"])
    injected = set(map(str, inj["issues"][key]))
    recon.append(f"| {cid} | {len(injected)} | {len(found)} | {'yes' if injected <= found else 'NO'} | {len(found - injected)} |")
rep = f"""# QA / Data-quality report

*Synthetic sample. Generated {dt.date.today()} by `scripts/export.py`; checks defined in `sql/03_dq_checks.sql`, handling in `sql/04_clean.sql`.*

## Check results (raw layer)

{md_table(dq)}

## Rows before / after cleaning

{md_table(counts)}

## Financial impact had the issues not been caught

* Duplicate bank-statement import: **EUR {impact.duplicate_payment_eur:,.2f}** of payments counted twice -> arrears understated by that amount.
* Orphan rent-roll lines (migrated units missing from unit master): **EUR {impact.quarantined_soll_eur:,.2f}** Soll quarantined.
* Duplicate ticket rows: **EUR {impact.duplicate_ticket_cost_eur:,.2f}** maintenance cost double-counted.

## Reconciliation against the injection log (proves the checks catch what was planted)

| check | injected keys | detected keys | all injected found | extra (natural) findings |
|---|---|---|---|---|
""" + "\n".join(recon) + "\n"
open("qa/dq_report.md", "w", encoding="utf-8").write(rep)
print("wrote qa/dq_report.md")

# ---------------------------------------------------------------- Power BI CSV exports (clean star schema)
tables = ["dim_property", "dim_unit", "dim_tenant", "dim_date", "dim_contractor", "dim_priority",
          "fact_rent_roll", "fact_payment", "fact_maintenance_ticket", "fact_vacancy_reletting",
          "fact_service_charge_statement", "fact_service_charge_cost", "fact_energy_monthly"]
for t in tables:
    con.execute(f"COPY core.{t} TO 'powerbi/csv/{t}.csv' (HEADER, DELIMITER ',')")
for t in ["rent_arrears_monthly", "occupancy_monthly"]:
    con.execute(f"COPY mart.{t} TO 'powerbi/csv/mart_{t}.csv' (HEADER, DELIMITER ',')")
print("exported powerbi/csv")
con.close()
